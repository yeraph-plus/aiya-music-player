-- 0009：把索引增强的关联表迁出应用库（docs/47 §P0）。
--
-- 一句话：`track_enrichment` 是 beets 模块的派生数据，不该出现在应用的
-- 数据模型里。它现在住在 `{app_data}/beets-index/enrich.db`，由
-- `crates/aiya-beets-store` 自己建表、自己迁移。
--
-- 这里只负责把 0008 留下的旧表收掉。**不迁移数据**：旧表里是分析缓存，
-- 重跑一遍就有；而跨库搬运要在启动路径上开第二个文件、处理它不存在/损坏/
-- 权限不足三种情况，为一个缓存付这个代价不值。
--
-- `IF EXISTS`：全新库根本没建过它（0008 已改成空文件）。
DROP TABLE IF EXISTS track_enrichment;
